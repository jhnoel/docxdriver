//! Reproducibly generate the public typed plan schema from the Rust API.
//! Run with `cargo run -p docxdriver-core --bin generate_typed_schema`.

use docxdriver_core::{Request, RequestResult};
use schemars::schema_for;
use serde_json::{json, Map, Value};
use std::fs;
use std::path::PathBuf;

fn main() {
    let schema = schema_for!(Request);
    let result_schema = schema_for!(RequestResult);
    let mut value = serde_json::to_value(schema).unwrap();
    let definitions = value
        .as_object_mut()
        .and_then(|root| root.remove("definitions"))
        .unwrap_or(Value::Object(Map::new()));
    let mut defs = Map::new();
    if let Some(entries) = definitions.as_object() {
        for (name, definition) in entries {
            let key = match name.as_str() {
                "EditOp" => "editOp".to_string(),
                "Plan" => "plan".to_string(),
                other => other.to_string(),
            };
            let mut definition = definition.clone();
            rewrite_refs(&mut definition);
            defs.insert(key, definition);
        }
    }
    if let Some(entries) = serde_json::to_value(result_schema)
        .unwrap()
        .get("definitions")
        .and_then(Value::as_object)
    {
        for (name, definition) in entries {
            let key = match name.as_str() {
                "EditOp" => "editOp".to_string(),
                "RequestResult" => "requestResult".to_string(),
                other => other.to_string(),
            };
            let mut definition = definition.clone();
            rewrite_refs(&mut definition);
            defs.entry(key).or_insert(definition);
        }
    }
    rewrite_refs(&mut value);
    value["$defs"] = Value::Object(defs);
    if let Some(defs) = value.get_mut("$defs").and_then(Value::as_object_mut) {
        defs.insert(
            "SourceHash".into(),
            json!({"type":"string","pattern":"^sha256:[0-9a-f]{64}$"}),
        );
        defs.insert(
            "Points".into(),
            json!({"type":"number","minimum":0,"multipleOf":0.05}),
        );
        defs.insert(
            "ParagraphAddress".into(),
            json!({"type":"string","pattern":"^(?:[A-F0-9]{8}|\\$[A-Za-z_][A-Za-z0-9_]*)$"}),
        );
        defs.insert(
            "InsertAnchor".into(),
            json!({"type":"string","pattern":"^(?:[A-F0-9]{8}|\\$[A-Za-z_][A-Za-z0-9_]*|table:[1-9][0-9]*)$"}),
        );
        defs.insert(
            "RevisionTarget".into(),
            json!({"type":"string","pattern":"^(?:all|[0-9]+)$"}),
        );
        defs.insert(
            "requestResult".into(),
            json!({"oneOf":[{"$ref":"#/$defs/CommandResult"},{"$ref":"#/$defs/PlanResult"}]}),
        );
    }
    value["$schema"] = Value::String("http://json-schema.org/draft-07/schema#".into());
    value["description"] = Value::String("Generated from crates/docxdriver-core/src/api.rs".into());
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let path = root.join("../../packages/docxdriver/schema/typed-request.schema.json");
    let schema_bytes = serde_json::to_vec_pretty(&value).unwrap();
    fs::write(path, &schema_bytes).unwrap();
    fs::write(
        root.join("../../packages/docxdriver-pi/schema/typed-request.schema.json"),
        &schema_bytes,
    )
    .unwrap();
    let typed = r#"/** Generated by crates/docxdriver-core/src/bin/generate_typed_schema.rs. */
export type SourceHash = `sha256:${string}`;
export type ChangeMode = 'track' | 'direct';
export type ParagraphAddress = string;
export type InsertAnchor = string;
export type ChromeKind = 'default' | 'first' | 'even';
export type Point = number;
export type InsertPosition = 'before' | 'after';
export type LineSpacing = { mode: 'multiple'; value: number } | { mode: 'exact'; value: Point } | { mode: 'at_least'; value: Point };
export type EditOp =
  | { op: 'replace_equation'; at: ParagraphAddress; mathml: string; equation?: number; display?: boolean }
  | { op: 'delete_equation'; at: ParagraphAddress; equation?: number }
  | { op: 'replace_text'; at: ParagraphAddress; select: string; with: string; occurrence?: number }
  | { op: 'replace_paragraph'; at: ParagraphAddress; with: string }
  | { op: 'format_text'; at: ParagraphAddress; select: string; occurrence?: number; bold?: boolean; italic?: boolean; underline?: boolean; strike?: boolean; superscript?: boolean; subscript?: boolean; color?: string; font_size?: Point; clear?: string[] }
  | { op: 'format_paragraph'; at: ParagraphAddress; style?: string; alignment?: 'left'|'center'|'right'|'justify'; indent_left?: Point; indent_right?: Point; space_before?: Point; space_after?: Point; line_spacing?: LineSpacing; clear?: string[] }
  | { op: 'insert_paragraph'; at: InsertAnchor; position: InsertPosition; with?: string; style?: string; as?: string }
  | { op: 'delete_paragraphs'; at: ParagraphAddress[] }
  | { op: 'set_page_margins'; section?: number; top?: Point; right?: Point; bottom?: Point; left?: Point; header?: Point; footer?: Point; gutter?: Point }
  | { op: 'set_even_and_odd_headers'; even_and_odd: boolean }
  | { op: 'set_header'; section?: number; kind?: ChromeKind; with: string }
  | { op: 'set_footer'; section?: number; kind?: ChromeKind; with: string }
  | { op: 'clear_header'; section?: number; kind?: ChromeKind }
  | { op: 'clear_footer'; section?: number; kind?: ChromeKind }
  | { op: 'comment_add'; at: ParagraphAddress; select?: string; occurrence?: number; text: string }
  | { op: 'comment_reply'; comment_id: string; text: string }
  | { op: 'comment_set_status'; comment_id: string; status: 'open'|'resolved' }
  | { op: 'comment_delete'; comment_id: string }
  | { op: 'revision_settle'; target: string; action: 'accept'|'reject' };
export type CreateCommand = { kind: 'create'; paragraphs?: string[]; html?: string };
export type ReadCommand = { kind: 'read'; read_kind?: 'document'|'document_ui'|'styles'|'comments'|'revisions'|'assets'; view?: 'markup'|'final'|'original' };
export type FindCommand = { kind: 'find'; query: string; ignore_case?: boolean; view?: 'markup'|'final'|'original' };
export type EditCommand = { kind: 'edit'; author: string; change_mode: ChangeMode; op: EditOp };
export type Command = CreateCommand | ReadCommand | FindCommand | EditCommand;
export type CommandRequest = { command: Command; expected_source?: SourceHash };
export type Plan = { base: SourceHash; author: string; change_mode: ChangeMode; ops: [EditOp, ...EditOp[]] };
export type PlanRequest = { plan: Plan; preview_key?: string };
export type PlanParseResult = { outcome: 'parsed'; plan: Plan } | { outcome: 'rejected'; diagnostic: Diagnostic };
export type Request = { Command: CommandRequest } | { Plan: PlanRequest };
export type Span = { line: number; column: number; end_line?: number; end_column?: number };
export type Diagnostic = { code: string; message: string; path?: string; span?: Span };
export type OperationReport = { index: number; op: string; outcome: string; summary: string; affected?: unknown[]; context_truncated?: boolean };
export type PlanReport = { completed: number; stopped_at?: number; ops: OperationReport[]; repaired_ids: string[]; allocated_ids: string[]; aliases: Record<string, unknown> };
export type CommandResult = { outcome: 'completed'; source?: SourceHash; result?: unknown; bytes?: Uint8Array } | { outcome: 'rejected'; source?: SourceHash; result?: unknown; diagnostic: Diagnostic };
export type PlanResult = { outcome: 'previewed'; source: SourceHash; plan: Plan; canonical_toml: string; preview_key: string; report: PlanReport } | { outcome: 'committed'; source: SourceHash; plan: Plan; canonical_toml: string; report: PlanReport; bytes: Uint8Array } | { outcome: 'rejected'; source?: SourceHash; plan?: Plan; diagnostic: Diagnostic; report?: PlanReport };
export type RequestResult = CommandResult | PlanResult;
"#;
    fs::write(root.join("../../packages/docxdriver/src/typed.ts"), typed).unwrap();
}

fn rewrite_refs(value: &mut Value) {
    match value {
        Value::String(text) => {
            if let Some(rest) = text.strip_prefix("#/definitions/") {
                let key = if rest == "EditOp" { "editOp" } else { rest };
                *text = format!("#/$defs/{key}");
            }
        }
        Value::Array(items) => items.iter_mut().for_each(rewrite_refs),
        Value::Object(map) => map.values_mut().for_each(rewrite_refs),
        Value::Null | Value::Bool(_) | Value::Number(_) => {}
    }
}
